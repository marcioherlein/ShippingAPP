import AxeBuilder from '@axe-core/playwright'
import { test, expect, browserTest } from './fixtures'
import { createManualProductAnalysis } from '../../src/lib/productConfirmation'
import { initialSupplierQuote } from '../../src/lib/supplierQuote'

for (const [width,entry] of [[390,'link'],[1440,'link'],[390,'search']] as const) test(`${entry}: focused quote saves the final dashboard at ${width}px`, async ({page},testInfo) => {
  await page.setViewportSize({width,height:900})
  const source='https://www.alibaba.com/product-detail/Tennis_1600000001234.html'
  const fixture=createManualProductAnalysis(source,'Raqueta de tenis de aluminio')
  Object.assign(fixture.product,{category:'Raqueta de tenis',material:'Aluminio',functionText:'Para jugar al tenis',originCountry:'China',unitPriceUsd:10,moq:1,packedWeightKg:0.1,volumeCbm:0.001,supplierQuote:initialSupplierQuote(10,true)})
  await page.route('**/api/opportunity-search',route=>route.fulfill({json:{status:'live',mode:'direct',query:'Raqueta tenis',note:'Proveedor de prueba',constraints:{maxUnitPriceUsd:null,maxMoq:null,originCountry:null,excludedOriginCountries:[],lowMoqPreference:false},constraintsNote:'',results:[{title:'Raqueta de tenis de aluminio',url:source,unitPriceUsd:10,priceDisplay:'USD 10',moq:1}]}}))
  await page.route('**/api/product-read',route=>route.fulfill({json:fixture}))
  await page.route('**/api/analyze',route=>route.fulfill({headers:{'x-shippingapp-usage-reservation':'fixture-reservation'},json:{...fixture,product:route.request().postDataJSON().product}}))
  let saved:any
  await page.route('**/api/history',route=>{saved=route.request().postDataJSON();return route.fulfill({status:201,json:{item:{id:'workspace-quote'}}})})
  await page.goto('/')
  await page.getByRole('button',{name:entry === 'search' ? /Quiero buscarlo/ : /Ya tengo un producto/}).click()
  await page.getByRole('radio',{name:'Reventa',exact:true}).click(); await page.getByRole('button',{name:'Continuar',exact:true}).click()
  await page.getByRole('radio',{name:'Empresa',exact:true}).click(); await page.getByRole('button',{name:'Continuar',exact:true}).click()
  await page.getByRole('radio',{name:'Sí',exact:true}).click()
  await page.getByRole('button',{name:/Seguir con presupuesto/}).click()
  await page.getByRole('radio',{name:/Tengo presupuesto/}).click(); await page.getByRole('button',{name:'Continuar',exact:true}).click()
  await page.getByLabel('Presupuesto máximo total').fill('10000')
  await page.getByRole('button',{name:/Seguir con el producto/}).click()
  if(entry === 'link') {
    await page.getByRole('button',{name:/Pegar link de Alibaba/}).click()
    await page.getByLabel('Enlace de Alibaba').fill(source)
    await page.getByRole('button',{name:/Leer producto/}).click()
  } else {
    await page.getByRole('textbox',{name:'Buscar productos en Alibaba'}).fill('Raqueta tenis')
    await page.getByRole('button',{name:'Buscar',exact:true}).click()
    await page.getByRole('button',{name:'Usar este producto',exact:true}).click()
  }
  await expect(page.locator('.case-question')).toBeVisible()
  await page.getByRole('button',{name:'Buscar en el nomenclador',exact:true}).click()
  await page.getByLabel('Producto o código NCM').fill('9506.51.00')
  await page.getByRole('radio',{name:/9506.51.00/}).check()
  await page.getByRole('checkbox',{name:/Revisé la descripción/}).check()
  await page.getByRole('button',{name:'Usar esta posición',exact:true}).click()
  await page.getByRole('button',{name:'Continuar',exact:true}).click()
  await page.getByRole('button',{name:'Continuar',exact:true}).click()
  await page.getByRole('button',{name:'Confirmar y calcular mis opciones',exact:true}).click()
  const result=page.getByRole('region',{name:'Tu presupuesto de importación'})
  await expect(result).toBeVisible()
  await expect(result.locator('.workspace-result-overview')).toContainText('Inversión total estimada')
  await expect(result.locator('details.workspace-audit')).not.toHaveAttribute('open','')
  await page.getByRole('button',{name:'Guardar presupuesto',exact:true}).click()
  await expect(page.getByRole('button',{name:'Presupuesto guardado',exact:true})).toBeVisible()
  expect(saved.result.purchasePlan.selected.cost.totalCostUsd).toBeLessThanOrEqual(10000)
  expect(saved.result.conversation.some((m:any)=>m.text==='Confirmo y calculo mi compra.')).toBe(true)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  const violations=(await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations.filter(v=>v.impact==='serious'||v.impact==='critical')
  expect(violations).toEqual([])
  await page.screenshot({path:testInfo.outputPath(`workspace-${width}.png`),fullPage:true})
})

